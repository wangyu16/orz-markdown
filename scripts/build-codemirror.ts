/**
 * Builds vendor/codemirror6.js — the pinned CodeMirror 6 bundle of the editor
 * shell — and writes src/carrier/editor/codemirror-pin.ts (versions, path,
 * SHA-384 integrity). Run `npm run build:codemirror` after changing a
 * `@codemirror/*` devDependency (they are pinned exactly in package.json);
 * tests/carrier-editor.test.ts fails when the bundle, the pin and the installed
 * versions disagree.
 *
 * The bundle is an IIFE setting `globalThis.OrzCodeMirror6`, loaded by a
 * `<script src integrity crossorigin>` (no eval, no inline script), and
 * script-safe (`<script` / `</script` written as `\x3C…`, as release bundles
 * are: spec/shell-runtime.md §6) so it may also be inlined.
 */
import { buildSync } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');

/** The packages whose code is in the bundle (direct imports of the entry and what they pull in). */
const CM_PACKAGES = [
  '@codemirror/state', '@codemirror/view', '@codemirror/commands', '@codemirror/language', '@codemirror/lang-markdown',
  '@codemirror/search', '@codemirror/autocomplete', '@lezer/common', '@lezer/highlight', '@lezer/lr', '@lezer/markdown',
] as const;

const versions: Record<string, string> = {};
for (const p of CM_PACKAGES) versions[p] = (JSON.parse(readFileSync(join(root, 'node_modules', p, 'package.json'), 'utf8')) as { version: string }).version;

const out = buildSync({
  entryPoints: [join(root, 'build', 'codemirror6-entry.mjs')],
  bundle: true, format: 'iife', globalName: 'OrzCodeMirror6', platform: 'browser', target: ['es2020'],
  minify: true, sourcemap: false, legalComments: 'eof', write: false, logLevel: 'warning',
  define: { __CM_VERSIONS__: JSON.stringify(versions) },
});
const code = out.outputFiles[0].text.replace(/<(\\*)(\/?script)/gi, '\\x3C$1$2');
const integrity = `sha384-${createHash('sha384').update(code, 'utf8').digest('base64')}`;
mkdirSync(join(root, 'vendor'), { recursive: true });
writeFileSync(join(root, 'vendor', 'codemirror6.js'), code);

const pin = `// Generated by scripts/build-codemirror.ts — do not edit. Rebuild with \`npm run build:codemirror\`.

/** The exact CodeMirror 6 package versions inside vendor/codemirror6.js. */
export const CODEMIRROR6_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2).replace(/\n}/, ',\n}')};

/** The bundle's path inside the orz-markdown package. */
export const CODEMIRROR6_PATH = 'vendor/codemirror6.js';

/** Subresource Integrity of the bundle's exact bytes. */
export const CODEMIRROR6_INTEGRITY = '${integrity}';

/** The bundle's size in bytes. */
export const CODEMIRROR6_BYTES = ${Buffer.byteLength(code, 'utf8')};

/** The global the bundle sets. */
export const CODEMIRROR6_GLOBAL = 'OrzCodeMirror6';
`;
const target = join(root, 'src', 'carrier', 'editor', 'codemirror-pin.ts');
mkdirSync(join(root, 'src', 'carrier', 'editor'), { recursive: true });
let current = '';
try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
if (current !== pin) writeFileSync(target, pin);
console.log(`vendor/codemirror6.js: ${Buffer.byteLength(code, 'utf8')} bytes, ${integrity}`);
