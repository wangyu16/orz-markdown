/**
 * Writes src/version.ts from package.json and the installed KaTeX, so the
 * published constants can never drift from the package that ships them.
 * Runs as `prebuild`; tests/hardening.test.ts fails if it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const require = createRequire(join(root, 'package.json'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };
const katex = require('katex/package.json') as { version: string };

const out = `// Generated by scripts/sync-version.ts from package.json — do not edit.

/** The orz-markdown version that produced this module. */
export const VERSION = '${pkg.version}';

/** The KaTeX version orz-markdown renders math with; its CSS must match. */
export const KATEX_VERSION = '${katex.version}';
`;

const target = join(root, 'src', 'version.ts');
let current = '';
try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
if (current !== out) {
  writeFileSync(target, out);
  console.log(`src/version.ts → ${pkg.version} (katex ${katex.version})`);
}
