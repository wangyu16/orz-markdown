/**
 * Generates orz-markdown-skills/assets/template.html from the same
 * preview-frame assets and runtime the carriers use, so the template an agent
 * copies can never lag the package (it used to embed a months-old runtime).
 * Also copies themes/common.css beside the starter theme assets/minimal.css.
 * Runs as part of `prebuild`; tests/skill-template.test.ts fails if stale.
 */
import { copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getPreviewFrameAssets } from '../src/preview-frame.js';

export function skillTemplate(): string {
  const pa = getPreviewFrameAssets();
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Document</title>
  <!-- GENERATED by scripts/build-skill-template.ts from orz-markdown's
       preview-frame assets — do not edit by hand (in the orz-markdown source
       repository, not in the package: \`npm run build\` regenerates it). -->

  <!-- Google Fonts preconnect hints (needed when using a theme with Google Fonts) -->
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>

  <!-- KaTeX CSS (version-matched to the KaTeX orz-markdown renders with) and the
       highlight.js stylesheet. For a dark theme, swap the #orz-hljs href to
       ${pa.cdn.hljsDarkCss} -->
  ${pa.headLinks('light')}

  <!-- Parser stylesheet — choose one of the bundled themes or link your own.
       Bundled themes (each imports common.css automatically):
         dark-elegant-1.css  dark-elegant-2.css  dark-elegant-3.css
         light-neat-1.css    light-neat-2.css    light-neat-3.css
         beige-decent-1.css  beige-decent-2.css
         light-academic-1.css light-academic-2.css
         light-playful-1.css  light-playful-2.css
       From the CDN: https://cdn.jsdelivr.net/npm/orz-markdown/themes/<name>.css
       Starter theme (neutral decoration; imports the common.css beside it —
       copy it to make a new theme): minimal.css                            -->
  <link rel="stylesheet" href="./minimal.css">
</head>
<body>

  <!-- All rendered HTML from md.render() goes inside this article element.
       The .markdown-body class is required — all theme styles are scoped under it. -->
  <article class="markdown-body">
    <!-- INSERT RENDERED HTML HERE -->
  </article>

  <!-- Content libraries (highlight.js, Mermaid, SmilesDrawer, Chart.js), the
       orz-markdown runtime (tabs, QR expand, copy-as-Markdown), and
       window.__orzEnhance(), which draws every generated construct. On a dark
       theme set window.__orzSmilesTheme = 'dark' before calling it. -->
  ${pa.bodyScripts()}
  <script>window.__orzEnhance();</script>

</body>
</html>
`;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop() ?? '');
if (isMain) {
  const assets = join(import.meta.dirname, '..', 'orz-markdown-skills', 'assets');
  writeFileSync(join(assets, 'template.html'), skillTemplate());
  // minimal.css (the starter theme) imports './common.css': ship the real one beside it.
  copyFileSync(join(import.meta.dirname, '..', 'themes', 'common.css'), join(assets, 'common.css'));
}
